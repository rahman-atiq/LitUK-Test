#!/usr/bin/env node
/**
 * Builds toughest-data.js from the authored question set.
 *
 *   node tools/build-toughest-data.mjs [--src DIR]
 *
 * Unlike the other four banks, this one is not a scrape. Its 480 questions were
 * written against the handbook chapters in this repo and the study guide they
 * render (https://britizen.uk/study-guide/), to drill the discriminations the
 * scraped banks mostly leave alone: the pairs the handbook itself sets up to be
 * confused — 1707 against 1801, 1807 against 1833, Bevan against Beveridge
 * against Butler, Holst against Elgar, Eid al-Fitr against Eid ul Adha.
 *
 * The source of truth is tools/data/toughest/t5*.json, one file per test, in
 * test-number order. Ids are assigned sequentially from FIRST_G in that order
 * and are LOAD-BEARING: saved progress is keyed on them, so a question may be
 * corrected in place but never reordered, and a retired question's id must be
 * left as a hole rather than reused. Same for the test numbers.
 *
 * Facts where the chapter pages in this repo and the live study guide disagree
 * are deliberately not asked: the Commonwealth's member count, the Northern
 * Ireland Assembly's seat count, the jury-service age range, the current
 * monarch, the National Lottery's minimum age and the Brexit date. The
 * disagreements are real (see tools/test-verify-bank.mjs, which pins three of
 * them as open findings) and a question that picks a side would be teaching one
 * edition's answer as if it were the other's.
 */
import fs from "node:fs";
import path from "node:path";
import { R } from "./lib/banks.mjs";

const argv = process.argv.slice(2);
const val = (f, d) => { const i = argv.indexOf(f); return i >= 0 && argv[i + 1] ? argv[i + 1] : d };

const SRC = val("--src", R("tools/data/toughest"));
const OUT = R("toughest-data.js");
const FIRST_G = 3198;          // INV-2: this bank's block starts here
const FIRST_N = 501;           // INV-3: and its test numbers here
const PER_TEST = 24;

const files = fs.readdirSync(SRC).filter((f) => /^t\d+\.json$/.test(f))
  .sort((a, b) => +a.match(/\d+/)[0] - +b.match(/\d+/)[0]);
if (!files.length) throw new Error(`no test files in ${SRC}`);

let g = FIRST_G;
const tests = files.map((f, i) => {
  const n = +f.match(/\d+/)[0];
  if (n !== FIRST_N + i) throw new Error(`${f} is out of order — expected t${FIRST_N + i}.json`);
  const t = JSON.parse(fs.readFileSync(path.join(SRC, f), "utf8"));
  if (t.q.length !== PER_TEST) throw new Error(`${f} has ${t.q.length} questions, expected ${PER_TEST}`);
  return { n, name: t.name, q: t.q.map((q) => ({ g: g++, t: q.t, e: q.e, p: q.p, o: q.o })) };
});

const header = `/* Question bank: 20 tests written against the handbook chapters in this repo
   and the study guide at britizen.uk, question ids ${FIRST_G}-${g - 1}, test numbers
   ${FIRST_N}-${FIRST_N + tests.length - 1}.
   Generated by tools/build-toughest-data.mjs — do not edit by hand.

   The only authored bank: the other four are third-party scrapes. These
   questions target the discriminations the handbook sets up and the scrapes
   under-drill — confusable date pairs, near-miss names, and the two-option
   twists. Ids and test numbers are load-bearing: saved progress is keyed on
   them, so never renumber. See tools/validate-banks.mjs. */
`;

const body = tests.map((t) => "    " + JSON.stringify(t)).join(",\n");
fs.writeFileSync(OUT, `${header}(window.LITUK_BANKS = window.LITUK_BANKS || []).push({
  id: "toughest",
  label: "Toughest Tests",
  source: "Britizen Study Guide",
  sourceUrl: "https://britizen.uk/study-guide/",
  passmark: 18,
  perTest: ${PER_TEST},
  tests: [
${body}
  ],
});
`);

console.log(`${OUT}: ${tests.length} tests · ${g - FIRST_G} questions · ids ${FIRST_G}-${g - 1} · tests ${FIRST_N}-${FIRST_N + tests.length - 1}`);
